// Compile the supplied design to a complete static page and native JS controls.
import { readFile, writeFile } from 'node:fs/promises';
import { parseHTML } from 'linkedom';
import { LandingPage } from '../site/landing.js';

const root = new URL('../', import.meta.url);
const { document } = parseHTML('<html><body>' + await readFile(new URL('site/landing.html', root), 'utf8') + '</body></html>');
const hoverRules = [];
const quote = JSON.stringify;
const escapeHTML = value => String(value ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const expression = value => value.match(/^\s*{{([\s\S]*?)}}\s*$/)?.[1].trim();
function interpolate(value) {
  const parts = value.split(/({{[\s\S]*?}})/);
  return parts.map(part => expression(part) ? `escapeHTML(${expression(part)})` : quote(escapeHTML(part))).join(' + ');
}
function compile(node) {
  if (node.nodeType === 3) return interpolate(node.textContent);
  if (node.nodeType !== 1) return '""';
  const tag = node.localName;
  const children = () => [...node.childNodes].map(compile).join(' + ') || '""';
  if (tag === 'sc-for') {
    return `${quote('<bt-list style="display:contents">')} + (${expression(node.getAttribute('list'))}).map((${node.getAttribute('as')}, $index) => ${children()}).join('') + ${quote('</bt-list>')}`;
  }
  if (tag === 'sc-if') return `((${expression(node.getAttribute('value'))}) ? (${children()}) : '')`;
  let code = quote('<' + tag);
  const hover = node.getAttribute('style-hover');
  if (hover) {
    const cls = 'bt-hover-' + hoverRules.length;
    hoverRules.push(`.${cls}:hover{${hover}}`);
    node.setAttribute('class', [node.getAttribute('class'), cls].filter(Boolean).join(' '));
  }
  for (const { name, value } of [...node.attributes]) {
    if (name === 'style-hover' || name.startsWith('hint-')) continue;
    if (/^on(click|change)$/i.test(name)) {
      const event = name.slice(2).toLowerCase();
      code += ` + ${quote(' data-bt-' + event + '="')} + on(${expression(value)}) + '\"'`;
    } else if (name === 'ref') {
      code += ` + ${quote(' data-bt-ref="' + expression(value) + '"')}`;
    } else if (['disabled', 'checked'].includes(name)) {
      code += ` + ((${expression(value) || quote(value)}) ? ${quote(' ' + name)} : '')`;
    } else {
      code += ` + ${quote(' ' + name + '="')} + (${interpolate(value)}) + '\"'`;
    }
  }
  code += ` + '>'`;
  if (!['img', 'input', 'br', 'hr', 'meta', 'link'].includes(tag)) code += ` + (${children()}) + ${quote('</' + tag + '>')}`;
  return code;
}
const instance = new LandingPage();
const keys = Object.keys(instance.renderVals());
const functionSource = `export function render(values, handlers) {\n  const { ${keys.join(', ')} } = values;\n  const on = handler => handlers.push(handler) - 1;\n  return ${[...document.body.childNodes].map(compile).join(' + ')};\n}\n`;
await writeFile(new URL('assets/render.js', root), '// Generated by npm run build. Edit site/landing.html.\n' + escapeHTML.toString().replace('value =>', 'const escapeHTML = value =>') + ';\n' + functionSource);
// Import after writing, including a cache buster for repeated builds.
const { render } = await import(new URL('assets/render.js?build=' + Date.now(), root));
const html = render(instance.renderVals(), []).replace(/[ \t]+$/gm, '');
await writeFile(new URL('assets/hover.css', root), '/* Generated by npm run build. */\n' + hoverRules.join('\n') + '\n');
await writeFile(new URL('assets/landing-page.js', root), '// Generated by npm run build. Edit site/landing.js.\n' + await readFile(new URL('site/landing.js', root), 'utf8'));
await writeFile(new URL('index.html', root), `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>BTrace 3.0 — Trace the live JVM</title>
  <meta name="description" content="Trace a running Java application with BTrace 3.0. One-line probes, coding-agent workflows, AI observability, and production-safe attach.">
  <meta name="theme-color" content="#201e1d">
  <link rel="icon" type="image/svg+xml" href="icon/btrace-icon-small.svg">
  <link rel="icon" type="image/png" sizes="32x32" href="icon/png/btrace-icon-32.png">
  <link rel="apple-touch-icon" href="icon/png/btrace-icon-180.png">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Oxanium:wght@500;600;700;800&family=JetBrains+Mono:wght@400;500;600;700&display=swap">
  <link rel="stylesheet" href="assets/design.css">
  <link rel="stylesheet" href="assets/landing.css">
  <link rel="stylesheet" href="assets/hover.css">
  <link rel="stylesheet" href="assets/site.css">
  <script type="module" src="assets/site.js"></script>
</head>
<body>
<a class="skip-link" href="#top">Skip to content</a>
<div id="landing">${html}</div>
<noscript><p class="no-script">Enable JavaScript to use the command builder, filters and demo selector. Documentation and installation links are available above.</p></noscript>
</body>
</html>\n`);
console.log('Built index.html and page assets.');
